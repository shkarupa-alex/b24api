def test_migration_module_is_a_leaf() -> None:
    tree = ast.parse(Path(migration.__file__).read_text(encoding="utf-8"))
    imported = {node.module for node in ast.walk(tree) if isinstance(node, ast.ImportFrom)}
    imported |= {alias.name for node in ast.walk(tree) if isinstance(node, ast.Import) for alias in node.names}

    assert not {module for module in imported if module and module.split(".")[0] == "b24api"}


def test_migration_guide_table_is_generated_from_the_map() -> None:
    guide = (ROOT / "docs" / "migration.md").read_text(encoding="utf-8")
    match = TABLE.search(guide)

    assert match is not None
    assert match["table"] == migration_table()
    assert "python -m b24api.migration" in guide
    rows = migration_table().splitlines()[2:]
    assert len(rows) == MOVED_COUNT
    assert all(
        f"`from {ROOT_MOVES[name]} import {name}`" in row for row, name in zip(rows, _table_names(rows), strict=True)
    )


def _table_names(rows: list[str]) -> list[str]:
    return [row.split("import ", 1)[1].split("`", 1)[0] for row in rows]



def _consumer_sources() -> list[tuple[str, str]]:
    sources: list[tuple[str, str]] = []
    for document in [ROOT / "README.md", *sorted((ROOT / "docs").rglob("*.md"))]:
        if "specifications" in document.relative_to(ROOT).parts:
            continue
        blocks = PYTHON_BLOCK.findall(document.read_text(encoding="utf-8"))
        sources.extend((f"{document.relative_to(ROOT)} block {index}", block) for index, block in enumerate(blocks))
    sources.extend(
        (str(path.relative_to(ROOT)), path.read_text(encoding="utf-8"))
        for path in sorted((ROOT / "examples").rglob("*.py"))
    )
    return sources


def _imported_modules(source: str) -> list[str]:
    modules: list[str] = []
    for node in ast.walk(ast.parse(source)):
        if isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
            modules.append(node.module)
        elif isinstance(node, ast.Import):
            modules.extend(alias.name for alias in node.names)
    return [module for module in modules if module.split(".")[0] == "b24api"]


def test_readme_docs_and_examples_import_only_public_namespaces() -> None:
    sources = _consumer_sources()
    leaked = [
        f"{name}: {module}"
        for name, source in sources
        for module in _imported_modules(source)
        if module not in PUBLIC_NAMESPACES
    ]

    assert len(sources) > MIN_CONSUMER_SOURCES
    assert leaked == []
    assert [str(finding) for name, source in sources for finding in scan_source(source, Path(name))] == []


